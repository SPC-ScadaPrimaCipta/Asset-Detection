"""
Detection V2 — Ground Truth annotation schema (Phase 8).

Human-authored ONLY. Never generated by CV, Gemini, or the pipeline —
evaluation would be circular otherwise. Predictions are matched against
this set; annotators must not view predictions before labeling.

Coordinate space: 0–1000 normalized (page-independent) + coordMethod
(visual-estimate | cad-measured). IoU thresholds must be interpreted
loosely until cad-measured annotations exist.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field


GT_STATUS = ("positive", "negative", "ambiguous", "unknown")
COORD_METHODS = ("visual-estimate", "cad-measured")


@dataclass
class GTBox:
    x: float = 0.0
    y: float = 0.0
    width: float = 0.0
    height: float = 0.0

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class GTAsset:
    id: str = ""
    bbox: GTBox = field(default_factory=GTBox)
    symbolLabel: str = ""          # Legend label, verbatim (e.g. "Vertical Pump")
    symbolId: str = ""             # Legend symbolId when known, else ""
    tag: str | None = None         # Normalized tag or None (tagless asset)
    tagRaw: str | None = None      # As printed (pre-normalization)
    tagBBox: GTBox | None = None
    status: str = "positive"       # positive|negative|ambiguous|unknown
    notes: str = ""

    def to_dict(self) -> dict:
        d = asdict(self)
        return d


@dataclass
class GTNegative:
    """Explicit non-asset: text/shape that must NOT become a detection."""
    id: str = ""
    bbox: GTBox = field(default_factory=GTBox)
    kind: str = ""                 # pipe-spec | title-text | marker | dimension | other
    text: str = ""
    notes: str = ""

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class GTPage:
    page: int = 1
    source: str = ""               # filename / snippet id
    coordMethod: str = "visual-estimate"
    conditions: dict = field(default_factory=dict)  # scanQuality, dpi, rotation,
    # noise, lineDensity, symbolSize, ocrDifficulty
    assets: list = field(default_factory=list)      # list[GTAsset dict]
    negatives: list = field(default_factory=list)   # list[GTNegative dict]
    annotator: str = ""
    version: str = "gt-v1"

    def to_dict(self) -> dict:
        return {"page": self.page, "source": self.source,
                "coordMethod": self.coordMethod, "conditions": self.conditions,
                "assets": [a if isinstance(a, dict) else a.to_dict() for a in self.assets],
                "negatives": [n if isinstance(n, dict) else n.to_dict() for n in self.negatives],
                "annotator": self.annotator, "version": self.version}

    def positives(self) -> list:
        return [a for a in self.assets
                if (a.get("status") if isinstance(a, dict) else a.status) == "positive"]
